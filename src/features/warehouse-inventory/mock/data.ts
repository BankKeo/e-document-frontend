import type { InventoryItem, StockMovement } from "../types";

function ago(minutes: number): string {
  return new Date(Date.now() - minutes * 60_000).toISOString();
}

function movement(
  type: StockMovement["type"],
  quantity: number,
  minutes: number
): StockMovement {
  return {
    id: `${type.toLowerCase()}-${minutes}`,
    at: ago(minutes),
    type,
    quantity,
    reference:
      type === "INBOUND"
        ? "GRN-2026-001"
        : type === "OUTBOUND"
          ? "ISS-2026-001"
          : type === "TRANSFER"
            ? "TRF-2026-001"
            : "ADJ-2026-001",
    actor: "Malinee Vongkham",
  };
}

